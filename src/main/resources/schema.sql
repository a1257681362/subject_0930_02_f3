-- H2 本地文件数据库初始化脚本。F1 在此基础上补充业务表。
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- ============================================================
-- aqua-1 海水养殖台账（第一版：建池、投苗、日常、抽检、出池；成本核算后续版本）
-- ============================================================

-- 养殖池档案：水深、盐度、所属海区
CREATE TABLE IF NOT EXISTS t_pond (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pond_code VARCHAR(32) NOT NULL,
    pond_name VARCHAR(64) NOT NULL,
    sea_area VARCHAR(64) NOT NULL,
    water_depth_m DECIMAL(6,2) NOT NULL,
    salinity_ppt DECIMAL(5,1) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pond_code UNIQUE (pond_code)
);

-- 投苗批次（原始投苗单）：苗种来源、入池数量、计划出池日
-- 不可删除：应用层不提供删除接口，表上不设逻辑删除标记。
CREATE TABLE IF NOT EXISTS t_seedling_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no VARCHAR(32) NOT NULL,
    pond_id BIGINT NOT NULL,
    species VARCHAR(64) NOT NULL,
    seed_source VARCHAR(128) NOT NULL,
    quantity INT NOT NULL,
    stock_date DATE NOT NULL,
    planned_harvest_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'STOCKED',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_batch_no UNIQUE (batch_no)
);
CREATE INDEX IF NOT EXISTS idx_batch_pond ON t_seedling_batch (pond_id);

-- 换池转移记录：批次在池间移动必须留痕
CREATE TABLE IF NOT EXISTS t_transfer_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    from_pond_id BIGINT NOT NULL,
    to_pond_id BIGINT NOT NULL,
    transfer_date DATE NOT NULL,
    quantity INT NOT NULL,
    reason VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_transfer_batch ON t_transfer_record (batch_id);

-- 日常记录：按池按批记录水质与死亡情况
CREATE TABLE IF NOT EXISTS t_daily_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pond_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    record_date DATE NOT NULL,
    water_depth_m DECIMAL(6,2),
    salinity_ppt DECIMAL(5,1),
    water_temp_c DECIMAL(5,2),
    mortality_count INT DEFAULT 0,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_daily_pond_batch ON t_daily_record (pond_id, batch_id);

-- 饲料投喂记录：按池按批留痕
CREATE TABLE IF NOT EXISTS t_feed_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pond_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    feed_date DATE NOT NULL,
    feed_name VARCHAR(64) NOT NULL,
    quantity_kg DECIMAL(8,2) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_feed_pond_batch ON t_feed_record (pond_id, batch_id);

-- 用药记录：按池按批留痕
CREATE TABLE IF NOT EXISTS t_medication_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pond_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    use_date DATE NOT NULL,
    medicine_name VARCHAR(64) NOT NULL,
    dosage VARCHAR(64) NOT NULL,
    reason VARCHAR(255),
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_medication_pond_batch ON t_medication_record (pond_id, batch_id);

-- 抽检记录
CREATE TABLE IF NOT EXISTS t_inspection_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pond_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    inspect_date DATE NOT NULL,
    sample_count INT NOT NULL,
    avg_weight_g DECIMAL(8,2),
    survival_rate DECIMAL(5,2),
    result VARCHAR(255),
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_inspection_pond_batch ON t_inspection_record (pond_id, batch_id);

-- 出池记录
CREATE TABLE IF NOT EXISTS t_harvest_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    pond_id BIGINT NOT NULL,
    harvest_date DATE NOT NULL,
    quantity INT NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_harvest_batch ON t_harvest_record (batch_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('aqua-1', '海水养殖台账：养殖池/投苗批次/转移/日常/饲料/用药/抽检/出池');

-- ============================================================
-- aqua-2 水质采样计划与缺测补录
-- 规则版本化：指标规则新版本只作用于未开始任务；
-- 采样值只追加不覆盖（补录独立成表）；
-- 主管审核通过后才进入池塘健康曲线；所有修改保留证据。
-- ============================================================

-- 指标规则版本：同一时刻仅一个 ACTIVE 版本（应用层保证，发布时旧版本置 SUPERSEDED）
CREATE TABLE IF NOT EXISTS t_wq_rule_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_rule_version_no UNIQUE (version_no)
);

-- 养殖阶段配置：阶段编码 + 采样频率（间隔天数）+ 适用的指标及正常范围
CREATE TABLE IF NOT EXISTS t_wq_stage_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    stage_code VARCHAR(32) NOT NULL,
    stage_name VARCHAR(64) NOT NULL,
    sample_interval_days INT NOT NULL,
    sort_no INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_stage_rule UNIQUE (version_id, stage_code)
);

-- 指标规则：某阶段下每个指标的正常范围（随版本快照，发布后不改）
CREATE TABLE IF NOT EXISTS t_wq_indicator_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_rule_id BIGINT NOT NULL,
    indicator_code VARCHAR(32) NOT NULL,
    indicator_name VARCHAR(64) NOT NULL,
    unit VARCHAR(16),
    min_value DECIMAL(12,3),
    max_value DECIMAL(12,3),
    required_flag BOOLEAN NOT NULL DEFAULT TRUE,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_indicator_rule UNIQUE (stage_rule_id, indicator_code)
);
CREATE INDEX IF NOT EXISTS idx_wq_ind_rule_stage ON t_wq_indicator_rule (stage_rule_id);

-- 水质采样计划：绑定规则版本、覆盖区间、适用养殖阶段
CREATE TABLE IF NOT EXISTS t_wq_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_no VARCHAR(32) NOT NULL,
    plan_name VARCHAR(64) NOT NULL,
    rule_version_id BIGINT NOT NULL,
    stage_code VARCHAR(32) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_plan_no UNIQUE (plan_no)
);
CREATE INDEX IF NOT EXISTS idx_wq_plan_version ON t_wq_plan (rule_version_id);

-- 计划覆盖的池塘：计划按池生成任务
CREATE TABLE IF NOT EXISTS t_wq_plan_pond (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL,
    pond_id BIGINT NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_plan_pond UNIQUE (plan_id, pond_id)
);
CREATE INDEX IF NOT EXISTS idx_wq_plan_pond_pond ON t_wq_plan_pond (pond_id);

-- 采样任务：按池按日生成，冻结当时的规则版本与阶段；状态 DRAFT/SUBMITTED/APPROVED/REJECTED
CREATE TABLE IF NOT EXISTS t_wq_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_no VARCHAR(40) NOT NULL,
    plan_id BIGINT NOT NULL,
    pond_id BIGINT NOT NULL,
    task_date DATE NOT NULL,
    stage_code VARCHAR(32) NOT NULL,
    rule_version_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    submitted_by BIGINT,
    submitted_time TIMESTAMP,
    reviewed_by BIGINT,
    reviewed_time TIMESTAMP,
    review_remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_task_no UNIQUE (task_no)
);
-- 按池按日按指标幂等：重复生成/重复提交请求不能产生第二条结果
CREATE INDEX IF NOT EXISTS idx_wq_task_plan_pond_date
    ON t_wq_task (plan_id, pond_id, task_date);

-- 任务测量项：每指标一行。提交时已测必须有值，缺测必须有原因
CREATE TABLE IF NOT EXISTS t_wq_task_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    indicator_code VARCHAR(32) NOT NULL,
    indicator_name VARCHAR(64) NOT NULL,
    unit VARCHAR(16),
    normal_min DECIMAL(12,3),
    normal_max DECIMAL(12,3),
    required_flag BOOLEAN NOT NULL DEFAULT TRUE,
    value_text VARCHAR(64),
    missing_flag BOOLEAN NOT NULL DEFAULT FALSE,
    missing_reason VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_task_item UNIQUE (task_id, indicator_code)
);
CREATE INDEX IF NOT EXISTS idx_wq_item_task ON t_wq_task_item (task_id);

-- 缺测/历史补录：只能追加新行，绝不覆盖原测量项；同一补录请求幂等
CREATE TABLE IF NOT EXISTS t_wq_backfill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_item_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    request_id VARCHAR(64),
    indicator_code VARCHAR(32) NOT NULL,
    value_text VARCHAR(64),
    missing_reason VARCHAR(255),
    backfill_date DATE NOT NULL,
    entry_type VARCHAR(16) NOT NULL DEFAULT 'MEASURED',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_backfill_request UNIQUE (request_id)
);
CREATE INDEX IF NOT EXISTS idx_wq_backfill_item ON t_wq_backfill (task_item_id);

-- 池塘健康曲线：只有主管审核通过的已测值才能进入（每任务每指标仅取一条）
CREATE TABLE IF NOT EXISTS t_wq_health_point (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pond_id BIGINT NOT NULL,
    task_id BIGINT NOT NULL,
    indicator_code VARCHAR(32) NOT NULL,
    indicator_name VARCHAR(64),
    unit VARCHAR(16),
    sample_date DATE NOT NULL,
    sample_value DECIMAL(12,3),
    task_rule_version_id BIGINT NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wq_health_point UNIQUE (task_id, indicator_code)
);
CREATE INDEX IF NOT EXISTS idx_wq_health_pond_ind_date
    ON t_wq_health_point (pond_id, indicator_code, sample_date);

-- 所有修改保留证据：记录对象、动作、操作前后 JSON 快照、请求幂等号
CREATE TABLE IF NOT EXISTS t_wq_change_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(32) NOT NULL,
    entity_id BIGINT NOT NULL,
    action VARCHAR(32) NOT NULL,
    request_id VARCHAR(64),
    before_json CLOB,
    after_json CLOB,
    detail VARCHAR(1000),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wq_evidence_entity ON t_wq_change_evidence (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_wq_evidence_request ON t_wq_change_evidence (request_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('aqua-2', '水质采样计划与缺测补录：阶段频率/指标范围版本化、按池生成任务、草稿/缺测原因、补录只追加、主管审核进健康曲线、修改留证');
