CREATE INDEX IF NOT EXISTS idx_wq_evidence_entity ON t_wq_change_evidence (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_wq_evidence_request ON t_wq_change_evidence (request_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('aqua-2', '水质采样计划与缺测补录：阶段频率/指标范围版本化、按池生成任务、草稿/缺测原因、补录只追加、主管审核进健康曲线、修改留证');

-- ============================================================
-- aqua-3 饲料批号与投喂配方
-- 饲料批号有生命周期与库存，过期/不足拦截；
-- 配方按苗种/日龄/水温匹配，版本化发布，投喂单锁定时冻结快照，历史投喂不随后续改版变化；
-- 投喂单锁定后才允许执行，临时减量必须登记原因与审批人；
-- 日汇总区分试喂与正式投喂；所有推进动作留证；
-- 海水养殖权限收紧时批号停止推进，配方版本保留已确认事实（只追加不删改）。
-- ============================================================

-- 饲料批号：批号全局唯一，登记入库、按投喂出库；状态只在应用层单向推进
CREATE TABLE IF NOT EXISTS t_feed_lot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_no VARCHAR(40) NOT NULL,
    feed_name VARCHAR(64) NOT NULL,
    manufacturer VARCHAR(128),
    production_date DATE,
    expiry_date DATE NOT NULL,
    stock_kg DECIMAL(10,2) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'IN_STOCK',
    frozen_flag BOOLEAN NOT NULL DEFAULT FALSE,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_feed_lot_no UNIQUE (lot_no)
);
CREATE INDEX IF NOT EXISTS idx_feed_lot_status ON t_feed_lot (status);

-- 批号流水：入库/出库/冻结只追加，库存以流水为事实来源
CREATE TABLE IF NOT EXISTS t_feed_lot_txn (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_id BIGINT NOT NULL,
    feed_order_id BIGINT,
    direction VARCHAR(8) NOT NULL,
    quantity_kg DECIMAL(10,2) NOT NULL,
    balance_kg DECIMAL(10,2) NOT NULL,
    reason VARCHAR(255),
    request_id VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_feed_lot_txn_lot ON t_feed_lot_txn (lot_id);
CREATE INDEX IF NOT EXISTS idx_feed_lot_txn_order ON t_feed_lot_txn (feed_order_id);

-- 投喂配方版本：同一时刻仅一个 ACTIVE 版本；发布新版本后旧版本 SUPERSEDED 但永不删改
CREATE TABLE IF NOT EXISTS t_feed_formula_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(255),
    published_time TIMESTAMP,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_feed_formula_version_no UNIQUE (version_no)
);

-- 配方行：按 苗种 + 日龄区间（天，闭区间）+ 水温区间（℃，闭区间）匹配投喂量
-- 行随版本快照，发布后不改；日龄/水温区间在同一版本同苗种内不得重叠
CREATE TABLE IF NOT EXISTS t_feed_formula_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id BIGINT NOT NULL,
    species VARCHAR(64) NOT NULL,
    day_age_from INT NOT NULL,
    day_age_to INT NOT NULL,
    water_temp_from_c DECIMAL(5,2) NOT NULL,
    water_temp_to_c DECIMAL(5,2) NOT NULL,
    feed_name VARCHAR(64) NOT NULL,
    dose_kg DECIMAL(8,3) NOT NULL,
    meal_count INT NOT NULL DEFAULT 1,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_feed_formula_item UNIQUE (version_id, species, day_age_from, day_age_to,
                                           water_temp_from_c, water_temp_to_c)
);
CREATE INDEX IF NOT EXISTS idx_feed_formula_item_match
    ON t_feed_formula_item (version_id, species);

-- 投喂单：锁定时冻结配方版本与行快照；只有 LOCKED 单才允许执行
-- feed_type: TRIAL 试喂 / FORMAL 正式投喂；减量必须有原因与审批人
