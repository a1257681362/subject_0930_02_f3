    planned_qty_kg DECIMAL(8,3) NOT NULL,
    actual_qty_kg DECIMAL(8,3),
    reduction_reason VARCHAR(255),
    reduction_approver VARCHAR(64),
    lot_id BIGINT,
    lot_no_snapshot VARCHAR(40),
    feed_name_snapshot VARCHAR(64),
    formula_snapshot CLOB,
    locked_time TIMESTAMP,
    locked_by BIGINT,
    executed_time TIMESTAMP,
    executed_by BIGINT,
    exec_request_id VARCHAR(64),
    create_request_id VARCHAR(64),
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_feed_order_no UNIQUE (order_no)
);
CREATE INDEX IF NOT EXISTS idx_feed_order_date_type ON t_feed_order (feed_date, feed_type);
CREATE INDEX IF NOT EXISTS idx_feed_order_batch ON t_feed_order (batch_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_feed_order_create_request
    ON t_feed_order (create_request_id);

